#include <string>
#include <vector>

void sum_range() {
    int acc = 0;
    for (int i = 10; i <= 20; ++i) acc += i;
    (void)acc;
}

void center_digit() {
    int n = 98765;
    int digits = 0;
    int temp = n;
    while (temp > 0) { digits += 1; temp /= 10; }
    for (int i = 1; i < digits / 2; ++i) n /= 10;
    int center = n % 10;
    (void)center;
}

void count_zeros() {
    int n = 102030;
    int zeros = 0;
    while (n > 0) { if (n % 10 == 0) zeros += 1; n /= 10; }
    (void)zeros;
}

void divisor_count() {
    int n = 36;
    int count = 0;
    for (int d = 1; d <= n; ++d) {
        if (n % d == 0) count += 1;
    }
    (void)count;
}

extern "C" int mellow_ember();
extern "C" void subtle_boulder();
extern "C" void amber_cove();
extern "C" void clever_maple();

int main() {
    sum_range();
    center_digit();
    count_zeros();
    divisor_count();
    subtle_boulder();
    amber_cove();
    clever_maple();
    return mellow_ember();
}
